#!/usr/bin/env node
/* Generate bilingual Coding-Decoding records for ALL remaining text-only questions.
 * Solved (rule verified + single option) -> full record appended to pinnacle-enhanced/Coding-Decoding.json
 * Abstained -> _Coding-Decoding.review.json (English + reason; NOT imported, "_" prefix is ignored by import glob)
 *
 * Hindi stem is RECONSTRUCTED from the parsed structure (examples/givens/target), which is safe:
 * a question is only "solved" when parse captured the exact pieces the verified rule reproduces,
 * so the reconstructed Hindi asks precisely the same question — and it avoids the junk-laden raw text.
 */
import fs from 'node:fs';
import { solve, parse } from './solver-coding.mjs';

const SRC = 'extract/pinnacle/Coding-Decoding.json';
const OUT = 'extract/pinnacle-enhanced/Coding-Decoding.json';
const REVIEW = 'extract/pinnacle-enhanced/_Coding-Decoding.review.json';

const clean = (s) => (s || '')
  .replace(/\s*www\.ssccglpinnacle\.com.*$/is, '')
  .replace(/\s*Download Pinnacle.*$/is, '')
  .replace(/\s*Pinnacle Coding-Decoding.*$/is, '')
  .replace(/\s+/g, ' ')
  .trim();

const ORD_HI = { 1: 'पहला', 2: 'दूसरा', 3: 'तीसरा', 4: 'चौथा', 5: 'पाँचवाँ', 6: 'छठा', '-1': 'अंतिम' };

// Reconstruct a clean Hindi question stem from parsed pieces.
function hindiStem(p) {
  const exList = p.examples.map(e => `‘${e.word}’ को ‘${e.code}’`).join(' और ');
  const givList = p.givens.map(g => `${g.word} = ${g.num}`).join(' और ');

  if (p.pickIndex !== null && p.pickIndex !== undefined && p.target) {
    const ord = ORD_HI[String(p.pickIndex)] || `${p.pickIndex}वाँ`;
    if (exList) return `एक कूट भाषा में ${exList} लिखा जाता है। उसी भाषा में ‘${p.target}’ के कूट का ${ord} अक्षर क्या होगा?`;
    if (givList) return `यदि ${givList} है, तो ‘${p.target}’ के कूट का ${ord} अक्षर क्या होगा?`;
  }
  if (p.targetCode) {   // DECODE
    if (exList) return `एक कूट भाषा में ${exList} लिखा जाता है। तो उसी भाषा में कौन-सा शब्द ‘${p.targetCode}’ के रूप में लिखा जाएगा?`;
    if (givList) return `यदि ${givList} है, तो कौन-सा शब्द ‘${p.targetCode}’ के रूप में लिखा जाएगा?`;
  }
  if (p.target) {       // ENCODE
    if (givList && !exList) return `यदि ${givList} है, तो उसी भाषा में ‘${p.target}’ को कैसे कोड किया जाएगा?`;
    if (exList) return `एक कूट भाषा में ${exList} लिखा जाता है। तो उसी भाषा में ‘${p.target}’ को कैसे लिखा जाएगा?`;
  }
  return null; // couldn't reconstruct -> caller will send to review
}

function difficulty(rule) {
  if (/permutation|product|reverse|sum\*2/.test(rule)) return 'hard';
  if (/^shift|^num:pos0|substitution|^num:pos$/.test(rule)) return 'easy';
  return 'medium';
}

const src = JSON.parse(fs.readFileSync(SRC, 'utf8')).filter(r => !r.has_fig);
const existing = JSON.parse(fs.readFileSync(OUT, 'utf8'));
// Only the 40 hand-built rows (book_q <= 40) are canonical/frozen; everything above is
// (re)generated by the solver, so re-running this script is idempotent.
const hand = existing.filter(r => r.book_q <= 40);
const doneBookQ = new Set(hand.map(r => r.book_q));

const solvedRecords = [];
const reviewRecords = [];
let noHindi = 0;

for (const s of src) {
  if (doneBookQ.has(s.book_q)) continue;
  const q = { ...s, opt_a: s.a, opt_b: s.b, opt_c: s.c, opt_d: s.d };
  const p = parse({ q: clean(s.q) });
  const r = solve({ q: clean(s.q), opt_a: s.a, opt_b: s.b, opt_c: s.c, opt_d: s.d });

  const oa = clean(s.a), ob = clean(s.b), oc = clean(s.c), od = clean(s.d);
  const base = {
    book_q: s.book_q,
    q: clean(s.q),
    exam: s.exam, date: s.date, shift: s.shift, year: s.year,
    opt_a: oa, opt_b: ob, opt_c: oc, opt_d: od,
    topic: 'Reasoning — Coding-Decoding',
    has_fig: false,
  };

  if (r.review) {
    reviewRecords.push({ ...base, needs_review: true, review_note: r.reason });
    continue;
  }

  const q_hi = hindiStem(p);
  if (!q_hi) { // solved but can't cleanly reconstruct Hindi -> flag rather than ship rough Hindi
    noHindi++;
    reviewRecords.push({ ...base, ans: r.ans, review_note: 'solved (' + r.rule + ') but Hindi stem needs manual phrasing' });
    continue;
  }

  // options: codes/numbers/candidate-words don't translate -> Hindi option = same token
  solvedRecords.push({
    ...base,
    q_hi,
    opt_a_hi: oa, opt_b_hi: ob, opt_c_hi: oc, opt_d_hi: od,
    ans: r.ans,
    expl_en: r.en,
    expl_hi: r.hi,
    trick_en: '', trick_hi: '',
    diff: difficulty(r.rule),
    _rule: r.rule,
  });
}

// merge solved into enhanced file (dedupe by book_q); strip internal _rule from output
const stripRule = ({ _rule, ...rest }) => rest;
const merged = hand.concat(solvedRecords.filter(r => !doneBookQ.has(r.book_q)).map(stripRule));
merged.sort((a, b) => a.book_q - b.book_q);
fs.writeFileSync(OUT, JSON.stringify(merged, null, 2) + '\n');
fs.writeFileSync(REVIEW, JSON.stringify(reviewRecords, null, 2) + '\n');

console.log(`source text-only      : ${src.length}`);
console.log(`already hand-done     : ${doneBookQ.size}`);
console.log(`newly SOLVED (added)  : ${solvedRecords.length}`);
console.log(`  of which no-Hindi   : ${noHindi} (sent to review instead)`);
console.log(`review file records   : ${reviewRecords.length}`);
console.log(`enhanced total now    : ${merged.length}  (answered bilingual)`);
console.log('');
console.log('solved-by-rule family:');
const byRule = {};
for (const r of solvedRecords) { const k = r._rule.split(':')[0].split('|')[0]; byRule[k] = (byRule[k] || 0) + 1; }
Object.entries(byRule).sort((a, b) => b[1] - a[1]).forEach(([k, v]) => console.log(`  ${v}\t${k}`));
console.log('');
console.log('sample new solved records:');
for (const r of solvedRecords.slice(0, 3)) {
  console.log(`  bq${r.book_q} ans=${r.ans} [${r._rule}]`);
  console.log(`     EN:  ${r.q}`);
  console.log(`     HI:  ${r.q_hi}`);
  console.log(`     sol: ${r.expl_hi}`);
}
